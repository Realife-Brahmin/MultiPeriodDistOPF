using LinearAlgebra, Libdl, Printf
BLAS.set_num_threads(1)
handle=Libdl.dlopen(ENV["MA97_SWEEP_LIBRARY"])
getthreads=Libdl.dlsym(handle,:omp_get_max_threads)
actual=ccall(getthreads,Cint,())
expected=parse(Int,ENV["OMP_SWEEP_THREADS"])
actual==expected || error("MA97 OpenMP threads $actual != $expected")
BLAS.get_num_threads()==1 || error("BLAS threads not one")
println("MA97_THREAD_RUNTIME expected=",expected," omp_max_threads=",actual," blas_threads=",BLAS.get_num_threads()," julia_threads=",Threads.nthreads())
println("MA97_RUNTIME_LIBRARIES ",filter(x->occursin(r"gomp|iomp|openblas|ma97",x),Libdl.dllist()))
println("MA97_CPU_AFFINITY ",match(r"(?m)^Cpus_allowed_list:\s*(.+)$",read("/proc/self/status",String)).captures[1])
wall_start=time_ns()
include(joinpath(@__DIR__,"repo","ddp","examples","power_system","centralized_ipopt_matched.jl"))
@printf("MA97_COMPLETE_WALL seconds=%.9f maxrss_bytes=%d\n",(time_ns()-wall_start)/1e9,Sys.maxrss())
